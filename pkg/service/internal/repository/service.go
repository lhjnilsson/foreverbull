const ServiceTable = `CREATE TABLE IF NOT EXISTS service (
image text PRIMARY KEY,
algorithm JSONB,
status int NOT NULL DEFAULT 0,
error TEXT);

CREATE TABLE IF NOT EXISTS service_status (
	id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	image text REFERENCES service(image) ON DELETE CASCADE,
	status int NOT NULL,
	error text,
	occurred_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE OR REPLACE FUNCTION notify_service_status() RETURNS TRIGGER AS $$
BEGIN
	-- Only update service_status if the status column is updated
	IF (TG_OP = 'UPDATE' AND OLD.status <> NEW.status) OR TG_OP = 'INSERT' THEN
		INSERT INTO service_status (image, status, error)
		VALUES (NEW.image, NEW.status, NEW.error);
		PERFORM pg_notify('service_status', NEW.image);
	END IF;
	RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DO
$$BEGIN
	CREATE TRIGGER service_status_trigger AFTER INSERT OR UPDATE ON service
	FOR EACH ROW EXECUTE PROCEDURE notify_service_status();
EXCEPTION
	WHEN duplicate_object THEN
		NULL;
END$$;
`

// MigrateServiceStatus adds service_status.id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY.
// Existing rows receive ids. It does not insert a status row. Calling it twice is safe.
func MigrateServiceStatus(ctx context.Context, conn postgres.Query) error {
	return migrateStatusIdentity(ctx, conn, "service_status")
}

type statusIDColumn struct {
	dataType           string
	identityGeneration string
	primaryKey         bool
}

func readStatusIDColumn(ctx context.Context, conn postgres.Query, table string) (statusIDColumn, error) {
	var column statusIDColumn
	err := conn.QueryRow(ctx, `
		SELECT
			COALESCE(c.data_type, ''),
			COALESCE(c.identity_generation, ''),
			EXISTS (
				SELECT 1
				FROM pg_constraint k
				JOIN pg_class rel ON rel.oid = k.conrelid
				JOIN pg_namespace n ON n.oid = rel.relnamespace
				JOIN pg_attribute a ON a.attrelid = rel.oid AND a.attnum = ANY (k.conkey)
				WHERE n.nspname = current_schema()
				  AND rel.relname = $1
				  AND k.contype = 'p'
				  AND a.attname = 'id'
				  AND array_length(k.conkey, 1) = 1
			)
		FROM (SELECT 1) AS seed
		LEFT JOIN information_schema.columns c
			ON c.table_schema = current_schema()
			AND c.table_name = $1
			AND c.column_name = 'id'`, table).Scan(
		&column.dataType, &column.identityGeneration, &column.primaryKey)
	if err != nil {
		return statusIDColumn{}, fmt.Errorf("%s: read id: %w", table, err)
	}
	return column, nil
}

type statusIdentitySQL struct {
	addColumn     string
	addIdentity   string
	addPrimaryKey string
	resetSequence string
	violations    string
}

func statusIdentityStatements(table string) (statusIdentitySQL, error) {
	switch table {
	case "service_status":
		return statusIdentitySQL{
			addColumn:     `ALTER TABLE service_status ADD COLUMN id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY`,
			addIdentity:   `ALTER TABLE service_status ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY`,
			addPrimaryKey: `ALTER TABLE service_status ADD PRIMARY KEY (id)`,
			resetSequence: `
				SELECT setval(
					pg_get_serial_sequence('service_status', 'id'),
					GREATEST(COALESCE((SELECT MAX(id) FROM service_status), 1), 1),
					COALESCE((SELECT MAX(id) FROM service_status), 0) <> 0)`,
			violations: `
				SELECT EXISTS (SELECT 1 FROM service_status WHERE id IS NULL)
					OR EXISTS (SELECT 1 FROM service_status GROUP BY id HAVING COUNT(*) > 1)`,
		}, nil
	case "service_instance_status":
		return statusIdentitySQL{
			addColumn:     `ALTER TABLE service_instance_status ADD COLUMN id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY`,
			addIdentity:   `ALTER TABLE service_instance_status ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY`,
			addPrimaryKey: `ALTER TABLE service_instance_status ADD PRIMARY KEY (id)`,
			resetSequence: `
				SELECT setval(
					pg_get_serial_sequence('service_instance_status', 'id'),
					GREATEST(COALESCE((SELECT MAX(id) FROM service_instance_status), 1), 1),
					COALESCE((SELECT MAX(id) FROM service_instance_status), 0) <> 0)`,
			violations: `
				SELECT EXISTS (SELECT 1 FROM service_instance_status WHERE id IS NULL)
					OR EXISTS (SELECT 1 FROM service_instance_status GROUP BY id HAVING COUNT(*) > 1)`,
		}, nil
	default:
		return statusIdentitySQL{}, fmt.Errorf("%s: unsupported status table", table)
	}
}

// migrateStatusIdentity adds the history primary key without inserting a status row.
// A null or duplicate id stays. Calling it twice is safe once the column is in place.
func migrateStatusIdentity(ctx context.Context, conn postgres.Query, table string) error {
	statements, err := statusIdentityStatements(table)
	if err != nil {
		return err
	}

	column, err := readStatusIDColumn(ctx, conn, table)
	if err != nil {
		return err
	}
	if column.dataType == "" {
		if _, err = conn.Exec(ctx, statements.addColumn); err != nil {
			return fmt.Errorf("%s: id primary key: %w", table, err)
		}
		return nil
	}
	if column.dataType != "bigint" {
		return fmt.Errorf("%s: id type %s is not bigint", table, column.dataType)
	}
	if column.identityGeneration == "BY DEFAULT" && column.primaryKey {
		return nil
	}
	if column.identityGeneration == "ALWAYS" {
		return fmt.Errorf("%s: id is not GENERATED BY DEFAULT AS IDENTITY", table)
	}

	var bad bool
	err = conn.QueryRow(ctx, statements.violations).Scan(&bad)
	if err != nil {
		return fmt.Errorf("%s: scan primary key: %w", table, err)
	}
	if bad {
		return fmt.Errorf("%s: rows violate primary key id", table)
	}

	if column.identityGeneration != "BY DEFAULT" {
		if _, err = conn.Exec(ctx, statements.addIdentity); err != nil {
			return fmt.Errorf("%s: id identity: %w", table, err)
		}
		if _, err = conn.Exec(ctx, statements.resetSequence); err != nil {
			return fmt.Errorf("%s: id sequence: %w", table, err)
		}
	}
	if !column.primaryKey {
		if _, err = conn.Exec(ctx, statements.addPrimaryKey); err != nil {
			return fmt.Errorf("%s: id primary key: %w", table, err)
		}
	}
	return nil
}

type Service struct {
	Conn postgres.Query
}

func (db *Service) Create(ctx context.Context, image string) (*pb.Service, error) {
	if environment.GetAuthEnabled() {
		return nil, fmt.Errorf("create service by image is refused while AUTH_ENABLED=true")
	}
	_, err := db.Conn.Exec(ctx,
		`INSERT INTO service (image) VALUES ($1)`,
		image,
	)
	if err != nil {
		return nil, fmt.Errorf("failed to create service: %w", err)
	}

	return db.Get(ctx, image)
}

func (db *Service) Get(ctx context.Context, image string) (*pb.Service, error) {
	if environment.GetAuthEnabled() {
		return db.getByImageJoined(ctx, image)
	}
	service := pb.Service{}

	rows, err := db.Conn.Query(ctx,
		`SELECT service.image, algorithm, ss.status, ss.error, ss.occurred_at
		FROM service
		INNER JOIN (
			SELECT image, status, error, occurred_at FROM service_status ORDER BY occurred_at DESC
		) ss ON service.image = ss.image
		WHERE service.image=$1`, image)
	if err != nil {
		return nil, fmt.Errorf("failed to get service: %w", err)
	}

	defer rows.Close()

	algorithm := []byte{}

	for rows.Next() {
		status := pb.Service_Status{}
		t := time.Time{}
		err = rows.Scan(
			&service.Image, &algorithm, &status.Status, &status.Error, &t,
		)
		status.OccurredAt = internal_pb.TimeToProtoTimestamp(t)

		if err != nil {
			return nil, fmt.Errorf("failed to get service: %w", err)
		}

		service.Statuses = append(service.Statuses, &status)
	}

	if service.Image == "" {
		return nil, errors.New("service not found")
	}

	if algorithm == nil {
		return &service, nil
	}

	err = json.Unmarshal(algorithm, &service.Algorithm)
	if err != nil {
		return nil, fmt.Errorf("failed to decode algorithm: %w", err)
	}

	return &service, nil
}

func (db *Service) SetAlgorithm(ctx context.Context, image string, a *pb.Algorithm) error {
	algorithm, err := json.Marshal(a)
	if err != nil {
		return fmt.Errorf("failed to encode algorithm: %w", err)
	}

	_, err = db.Conn.Exec(ctx,
		`UPDATE service SET algorithm=$2 WHERE image=$1`,
		image, algorithm,
	)
	if err != nil {
		return fmt.Errorf("failed to set algorithm: %w", err)
	}

	return nil
}

func (db *Service) UpdateStatus(ctx context.Context, image string, status pb.Service_Status_Status, err error) error {
	if err != nil {
		_, err = db.Conn.Exec(ctx,
			`UPDATE service SET status=$2, error=$3 WHERE image=$1`,
			image, status, err.Error(),
		)
	} else {
		_, err = db.Conn.Exec(ctx,
			`UPDATE service SET status=$2 WHERE image=$1`,
			image, status,
		)
	}

	if err != nil {
		return fmt.Errorf("failed to update status: %w", err)
	}

	return nil
}

func (db *Service) List(ctx context.Context) ([]*pb.Service, error) {
	if environment.GetAuthEnabled() {
		return nil, fmt.Errorf("list services is refused while AUTH_ENABLED=true")
	}
	rows, err := db.Conn.Query(ctx,
		`SELECT service.image, algorithm, ss.status, ss.error, ss.occurred_at
		FROM service
		INNER JOIN (
			SELECT image, status, error, occurred_at FROM service_status ORDER BY occurred_at DESC
		) ss ON service.image = ss.image
		ORDER BY ss.occurred_at ASC`)
	if err != nil {
		return nil, fmt.Errorf("failed to list services: %w", err)
	}
	defer rows.Close()

	services := []*pb.Service{}

	var inReturnSlice bool

	for rows.Next() {
		serviceStatus := pb.Service_Status{}
		occurredAt := time.Time{}
		service := pb.Service{}
		algorithm := []byte{}

		err = rows.Scan(
			&service.Image, &algorithm, &serviceStatus.Status, &serviceStatus.Error, &occurredAt,
		)
		if err != nil {
			return nil, fmt.Errorf("failed to list services: %w", err)
		}

		serviceStatus.OccurredAt = internal_pb.TimeToProtoTimestamp(occurredAt)

		inReturnSlice = false

		for i := range services {
			if services[i].Image == service.Image {
				services[i].Statuses = append(services[i].Statuses, &serviceStatus)
				inReturnSlice = true
			}
		}

		if !inReturnSlice {
			service.Statuses = append(service.Statuses, &serviceStatus)
			services = append(services, &service)
		}

		if algorithm == nil {
			continue
		}

		err = json.Unmarshal(algorithm, &service.Algorithm)
		if err != nil {
			return nil, fmt.Errorf("failed to decode algorithm: %w", err)
		}
	}

	return services, nil
}

func (db *Service) Delete(ctx context.Context, image string) error {
	if environment.GetAuthEnabled() {
		return fmt.Errorf("delete service by image is refused while AUTH_ENABLED=true")
	}
	_, err := db.Conn.Exec(ctx,
		"DELETE FROM service WHERE image=$1", image)
	if err != nil {
		return fmt.Errorf("failed to delete service: %w", err)
	}

	return nil
}
